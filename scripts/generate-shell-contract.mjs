#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const check = process.argv.includes('--check')
const normalize = (value) => value.replace(/\r\n?/g, '\n')
const readJson = (relative) => JSON.parse(readFileSync(path.join(root, relative), 'utf8'))

const contract = readJson('protocol/shell-contract.json')
const pluginPackage = readJson('packages/plugin-harness-shell/package.json')
const hostProtocol = readJson('protocol/host-protocol-v2.json')

if (contract.schemaVersion !== 1) throw new Error(`unsupported shell contract schemaVersion ${contract.schemaVersion}`)
if (!Number.isInteger(contract.apiVersion) || contract.apiVersion <= 0) throw new Error('shell apiVersion must be a positive integer')
if (contract.pluginId !== 'harness-shell') throw new Error(`unexpected shell pluginId ${contract.pluginId}`)
if (!Array.isArray(contract.commands) || contract.commands.length === 0) throw new Error('shell contract has no commands')

const names = new Set()
const direct = {}
const host = {}
const hostWireNames = new Set(hostProtocol.commands.map((row) => row.wire))
for (const row of contract.commands) {
  if (!row || typeof row.name !== 'string' || typeof row.target !== 'string') {
    throw new Error('shell command rows require string name/target')
  }
  if (names.has(row.name)) throw new Error(`duplicate shell command ${row.name}`)
  names.add(row.name)
  if (row.route === 'direct') direct[row.name] = row.target
  else if (row.route === 'host') {
    if (!hostWireNames.has(row.target)) throw new Error(`shell host command ${row.name} targets unknown Host Protocol command ${row.target}`)
    host[row.name] = row.target
  } else {
    throw new Error(`shell command ${row.name} has unsupported route ${row.route}`)
  }
}

const commandNames = [...names]
const generatedTs = `// @generated by scripts/generate-shell-contract.mjs. DO NOT EDIT.\n` +
  `export const SHELL_API_VERSION = ${contract.apiVersion} as const\n` +
  `export const SHELL_PLUGIN_ID = ${JSON.stringify(contract.pluginId)} as const\n` +
  `export const SHELL_VERSION = ${JSON.stringify(pluginPackage.version)} as const\n` +
  `export const SHELL_COMMANDS = ${JSON.stringify(commandNames, null, 2)} as const\n`

const generatedRust = `// @generated by scripts/generate-shell-contract.mjs. DO NOT EDIT.\n\n` +
  `pub const SHELL_API_VERSION: u16 = ${contract.apiVersion};\n` +
  `pub const SHELL_PLUGIN_ID: &str = ${JSON.stringify(contract.pluginId)};\n` +
  `pub const SHELL_VERSION: &str = ${JSON.stringify(pluginPackage.version)};\n` +
  `pub const SHELL_DIRECT_WINDOW_MAP_JSON: &str = r#${JSON.stringify(JSON.stringify(direct))}#;\n` +
  `pub const SHELL_HOST_COMMAND_MAP_JSON: &str = r#${JSON.stringify(JSON.stringify(host))}#;\n`

const manifest = `${JSON.stringify({
  id: contract.pluginId,
  name: 'Harness Shell',
  version: pluginPackage.version,
  kind: 'shell',
  apiVersion: contract.apiVersion,
  entry: 'lib/index.js',
  webEntry: 'web/shell.js',
  safeMode: true,
  requires: [],
}, null, 2)}\n`

const outputs = [
  ['packages/bootstrap/src/shell-contract.generated.ts', generatedTs],
  ['packages/plugin-harness-shell/src/shell-contract.generated.ts', generatedTs],
  ['apps/tauri/src-tauri/src/shell_contract_generated.rs', generatedRust],
  ['packages/plugin-harness-shell/manifest.json', manifest],
]

let stale = false
for (const [relative, expected] of outputs) {
  const target = path.join(root, relative)
  if (check) {
    let actual = ''
    try { actual = readFileSync(target, 'utf8') } catch {}
    if (normalize(actual) !== normalize(expected)) {
      console.error(`[shell-contract] stale generated file: ${relative}`)
      stale = true
    }
  } else {
    writeFileSync(target, normalize(expected), 'utf8')
  }
}

if (stale) process.exit(1)
if (check) console.log(`[shell-contract] apiVersion=${contract.apiVersion}; ${commandNames.length} commands; generated consumers synchronized`)
