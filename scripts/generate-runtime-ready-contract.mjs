#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const check = process.argv.includes('--check')
const normalize = (value) => value.replace(/\r\n?/g, '\n')
const contract = JSON.parse(readFileSync(path.join(root, 'protocol', 'runtime-ready-contract.json'), 'utf8'))

if (contract.schemaVersion !== 1) throw new Error(`unsupported runtime ready schemaVersion ${contract.schemaVersion}`)
if (contract.loopbackHost !== '127.0.0.1') throw new Error('runtime ready contract must remain loopback-only')
const requiredEnv = ['readyFile', 'dshVersion', 'generation', 'nonce', 'imageIdentity']
for (const key of requiredEnv) {
  if (typeof contract.env?.[key] !== 'string' || contract.env[key].length === 0) {
    throw new Error(`runtime ready contract missing env.${key}`)
  }
}
const requiredFields = ['url', 'host', 'port', 'pid', 'dshVersion', 'generation', 'nonce', 'imageIdentity']
if (JSON.stringify(contract.fields) !== JSON.stringify(requiredFields)) {
  throw new Error(`runtime ready fields must be exactly ${requiredFields.join(', ')}`)
}

const generatedTs = `// @generated by scripts/generate-runtime-ready-contract.mjs. DO NOT EDIT.\n` +
  `export const RUNTIME_READY_LOOPBACK_HOST = ${JSON.stringify(contract.loopbackHost)} as const\n` +
  `export const RUNTIME_READY_ENV = Object.freeze(${JSON.stringify(contract.env, null, 2)})\n` +
  `export const RUNTIME_READY_FIELDS = ${JSON.stringify(contract.fields, null, 2)} as const\n`

const rustName = (value) => value.replace(/([a-z])([A-Z])/g, '$1_$2').toUpperCase()
const generatedRust = `// @generated by scripts/generate-runtime-ready-contract.mjs. DO NOT EDIT.\n\n` +
  `pub const RUNTIME_READY_LOOPBACK_HOST: &str = ${JSON.stringify(contract.loopbackHost)};\n` +
  Object.entries(contract.env)
    .map(([key, value]) => `pub const RUNTIME_READY_ENV_${rustName(key)}: &str = ${JSON.stringify(value)};`)
    .join('\n') + '\n'

const outputs = [
  ['packages/client-runtime/src/runtime-ready-contract.generated.ts', generatedTs],
  ['packages/plugin-embedded-client/src/runtime-ready-contract.generated.ts', generatedTs],
  ['apps/tauri/src-tauri/src/runtime_ready_contract_generated.rs', generatedRust],
]

let stale = false
for (const [relative, expected] of outputs) {
  const target = path.join(root, relative)
  if (check) {
    let actual = ''
    try { actual = readFileSync(target, 'utf8') } catch {}
    if (normalize(actual) !== normalize(expected)) {
      console.error(`[runtime-ready-contract] stale generated file: ${relative}`)
      stale = true
    }
  } else {
    writeFileSync(target, normalize(expected), 'utf8')
  }
}

if (stale) process.exit(1)
if (check) console.log(`[runtime-ready-contract] ${requiredFields.length} fields and ${requiredEnv.length} env bindings synchronized`)
