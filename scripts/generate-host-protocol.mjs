import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const schemaPath = path.join(root, 'protocol', 'host-protocol-v2.json')
const schema = JSON.parse(readFileSync(schemaPath, 'utf8'))
const check = process.argv.includes('--check')

const rustEnum = (name, rows, attrs = '') => `#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]\n${attrs}pub enum ${name} {\n${rows.map((row) => `    #[serde(rename = ${JSON.stringify(row.wire)})]\n    ${row.rust},`).join('\n')}\n}\n`

const rust = `// @generated by scripts/generate-host-protocol.mjs. DO NOT EDIT.\n\npub const HOST_PROTOCOL_VERSION: u16 = ${schema.version};\n\n${rustEnum('SubjectKind', schema.subjects)}\n${rustEnum('Capability', schema.capabilities)}\n#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]\n#[serde(tag = "type")]\npub enum HostCommand {\n${schema.commands.map((row) => `    #[serde(rename = ${JSON.stringify(row.wire)})]\n    ${row.rust},`).join('\n')}\n}\n\nimpl HostCommand {\n    pub const fn capability(&self) -> Capability {\n        match self {\n${schema.commands.map((row) => `            Self::${row.rust} => Capability::${row.capability},`).join('\n')}\n        }\n    }\n}\n`

const js = `// @generated by scripts/generate-host-protocol.mjs. DO NOT EDIT.\nexport const HOST_PROTOCOL_VERSION = ${schema.version}\nexport const HOST_SUBJECTS = Object.freeze(${JSON.stringify(Object.fromEntries(schema.subjects.map((row) => [row.rust, row.wire])), null, 2)})\nexport const HOST_CAPABILITIES = Object.freeze(${JSON.stringify(Object.fromEntries(schema.capabilities.map((row) => [row.rust, row.wire])), null, 2)})\nexport const HOST_COMMANDS = Object.freeze(${JSON.stringify(Object.fromEntries(schema.commands.map((row) => [row.rust, row.wire])), null, 2)})\nexport const HOST_COMMAND_CAPABILITIES = Object.freeze(${JSON.stringify(Object.fromEntries(schema.commands.map((row) => [row.wire, schema.capabilities.find((cap) => cap.rust === row.capability)?.wire])), null, 2)})\n`

const markdown = `# Host Protocol v${schema.version} generated contract\n\n> Generated from \`protocol/host-protocol-v2.json\`. Do not edit by hand.\n\n## Commands\n\n| Command | Capability |\n| --- | --- |\n${schema.commands.map((row) => `| \`${row.wire}\` | \`${schema.capabilities.find((cap) => cap.rust === row.capability)?.wire}\` |`).join('\n')}\n\n## Subjects\n\n${schema.subjects.map((row) => `- \`${row.wire}\``).join('\n')}\n\n## Capabilities\n\n${schema.capabilities.map((row) => `- \`${row.wire}\``).join('\n')}\n`

const outputs = [
  ['apps/tauri/src-tauri/src/host_protocol_generated.rs', rust],
  ['packages/plugin-harness-shell/src/host-protocol.generated.js', js],
  ['docs/reference/host-protocol-v2.generated.md', markdown],
]

let stale = false
for (const [relative, content] of outputs) {
  const target = path.join(root, relative)
  if (check) {
    let actual = ''
    try { actual = readFileSync(target, 'utf8') } catch {}
    if (actual !== content) {
      console.error(`[host-protocol] stale generated file: ${relative}`)
      stale = true
    }
  } else {
    writeFileSync(target, content, 'utf8')
  }
}

if (stale) process.exit(1)
if (check) console.log('[host-protocol] canonical schema and generated artifacts are synchronized')
